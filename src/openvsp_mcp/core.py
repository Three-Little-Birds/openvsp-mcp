"""Isolated OpenVSP execution with retained artifacts and checked completion."""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import tempfile
from pathlib import Path
from shutil import which
from xml.etree import ElementTree as ET

from .models import OpenVSPRequest, OpenVSPResponse

COMPLETION_MARKER = "OPENVSP_MCP_COMPLETE"
ERROR_MARKER = "OPENVSP_MCP_API_ERROR:"
VERSION_MARKER = "OPENVSP_MCP_VERSION:"
_OK_EXIT_CODES = {0, 160, 224}


def _resolve_binary(env_var: str, default_name: str) -> str:
    candidate = os.environ.get(env_var) or which(default_name) or default_name
    return str(Path(candidate).expanduser().resolve()) if Path(candidate).exists() else candidate


OPENVSP_BIN = _resolve_binary("OPENVSP_BIN", "vsp")
VSPAERO_BIN = _resolve_binary("VSPAERO_BIN", "vspaero")


def create_run_directory(output_directory: str | None = None) -> Path:
    parent = Path(output_directory or os.environ.get("OPENVSP_OUTPUT_DIR", "openvsp-artifacts"))
    parent = parent.expanduser().resolve()
    try:
        parent.mkdir(parents=True, exist_ok=True)
        return Path(tempfile.mkdtemp(prefix="run_", dir=parent))
    except OSError as exc:
        raise RuntimeError(f"Cannot create artifact directory in {parent}: {exc}") from exc


def script_string(value: str | Path) -> str:
    """Quote paths for AngelScript, including backslashes and embedded quotes."""
    return json.dumps(str(value), ensure_ascii=False)


def write_model_script(commands: list[str], script_path: Path, geometry_path: Path) -> Path:
    error_check = [
        "    if (GetNumTotalErrors() > 0) {",
        "        while (GetNumTotalErrors() > 0) {",
        "            ErrorObj err = PopLastError();",
        f'            Print("{ERROR_MARKER}" + err.GetErrorString());',
        "        }",
        "        return 1;",
        "    }",
    ]
    lines = [
        "// Auto-generated by openvsp-mcp",
        "int main() {",
        f'    Print("{VERSION_MARKER}" + GetVSPVersion());',
        "    ClearVSPModel();",
        f"    SetVSP3FileName({script_string(geometry_path)});",
        *(f"    {command}" for command in commands),
        "    Update();",
        *error_check,
        f"    WriteVSPFile({script_string(geometry_path)}, SET_ALL);",
        *error_check,
        f'    Print("{COMPLETION_MARKER}");',
        "    return 0;",
        "}",
    ]
    script_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return script_path


def _as_text(value: str | bytes | None) -> str:
    if isinstance(value, bytes):
        return value.decode("utf-8", errors="replace")
    return value or ""


def _run_logged(
    args: list[str], workdir: Path, timeout: float, label: str
) -> subprocess.CompletedProcess[str]:
    try:
        result = subprocess.run(
            args,
            cwd=workdir,
            check=False,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=timeout,
        )
    except FileNotFoundError as exc:
        raise RuntimeError(
            f"{label} binary not found: {args[0]}. Set {label.upper()}_BIN to its executable path."
        ) from exc
    except subprocess.TimeoutExpired as exc:
        (workdir / f"{label}.stdout.log").write_text(_as_text(exc.stdout), encoding="utf-8")
        (workdir / f"{label}.stderr.log").write_text(_as_text(exc.stderr), encoding="utf-8")
        raise RuntimeError(f"{label} exceeded {timeout:g} seconds; artifacts: {workdir}") from exc
    except OSError as exc:
        raise RuntimeError(f"Cannot execute {label} binary {args[0]}: {exc}") from exc
    (workdir / f"{label}.stdout.log").write_text(result.stdout, encoding="utf-8")
    (workdir / f"{label}.stderr.log").write_text(result.stderr, encoding="utf-8")
    return result


def run_openvsp(script_path: Path, geometry_path: Path, timeout: float) -> str:
    result = _run_logged(
        [_resolve_binary("OPENVSP_BIN", "vsp"), "-script", str(script_path)],
        script_path.parent,
        timeout,
        "openvsp",
    )
    output = result.stdout + "\n" + result.stderr
    lines = [line.strip() for line in result.stdout.splitlines()]
    if (
        result.returncode not in _OK_EXIT_CODES
        or ERROR_MARKER in output
        or COMPLETION_MARKER not in lines
    ):
        raise RuntimeError(
            f"OpenVSP did not complete successfully (exit {result.returncode}); "
            f"artifacts: {script_path.parent}\n{output.strip()[-4000:]}"
        )
    try:
        if ET.parse(geometry_path).getroot().tag != "Vsp_Geometry":
            raise ValueError("Unexpected XML root")
    except (OSError, ET.ParseError, ValueError) as exc:
        raise RuntimeError(
            f"OpenVSP did not produce a valid model at {geometry_path}: {exc}"
        ) from exc
    versions = [
        line.removeprefix(VERSION_MARKER).strip()
        for line in lines
        if line.startswith(VERSION_MARKER)
    ]
    return versions[-1] if versions else "unknown"


def execute_openvsp(request: OpenVSPRequest) -> OpenVSPResponse:
    source = Path(request.geometry_file).expanduser().resolve()
    if not source.is_file():
        raise RuntimeError(f"Geometry file not found: {source}")
    case_base = Path(request.case_name).expanduser().resolve()
    if request.run_vspaero and not Path(f"{case_base}.vspaero").is_file():
        raise RuntimeError(f"VSPAero requires configured solver inputs at {case_base}.vspaero")
    workdir = create_run_directory(request.output_directory)
    geometry_path = workdir / "model.vsp3"
    script_path = _write_script(
        request.model_copy(update={"geometry_file": str(source)}), workdir, geometry_path
    )
    (workdir / "request.json").write_text(request.model_dump_json(indent=2), encoding="utf-8")
    run_openvsp(script_path, geometry_path, request.timeout_seconds)

    # Commit only a complete native run; the snapshot in workdir remains reproducible.
    staging_path: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(
            dir=source.parent, prefix=".openvsp_", suffix=".vsp3", delete=False
        ) as staging:
            staging_path = Path(staging.name)
        shutil.copy2(geometry_path, staging_path)
        os.replace(staging_path, source)
    except OSError as exc:
        raise RuntimeError(
            f"Cannot replace {source}; completed model is retained at {geometry_path}: {exc}"
        ) from exc
    finally:
        if staging_path is not None:
            staging_path.unlink(missing_ok=True)

    result_path: str | None = None
    if request.run_vspaero:
        # The standalone solver takes a case base, with preconfigured mesh and inputs.
        adb = Path(f"{case_base}.adb")
        prior = adb.stat() if adb.is_file() else None
        aero = _run_logged(
            [_resolve_binary("VSPAERO_BIN", "vspaero"), str(case_base)],
            workdir,
            request.timeout_seconds,
            "vspaero",
        )
        current = adb.stat() if adb.is_file() else None
        unchanged = (
            prior is not None
            and current is not None
            and (prior.st_mtime_ns, prior.st_size) == (current.st_mtime_ns, current.st_size)
        )
        if aero.returncode != 0 or current is None or current.st_size == 0 or unchanged:
            raise RuntimeError(
                f"VSPAero failed or produced no ADB; artifacts: {workdir}\n{aero.stderr[-4000:]}"
            )
        result_path = str(adb)
    return OpenVSPResponse(
        script_path=str(script_path),
        result_path=result_path,
        geometry_path=str(source),
        artifact_directory=str(workdir),
    )


def _ensure_statement(command: str) -> str:
    stripped = command.strip()
    return stripped if stripped.endswith(";") else f"{stripped};"


def _write_script(
    request: OpenVSPRequest, working_dir: Path, output_file: Path | None = None
) -> Path:
    commands = [f"ReadVSPFile({script_string(request.geometry_file)});"]
    commands.extend(_ensure_statement(command.command) for command in request.set_commands)
    return write_model_script(
        commands, working_dir / "automation.vspscript", output_file or Path(request.geometry_file)
    )
